package com.ambulanceservice.systemtest;

import java.util.LinkedHashMap;
import java.util.Map;

public final class ApiTestDataFactory {

    private ApiTestDataFactory() {
    }

    public static String uniqueEmail(String label) {
        return TestDataCleanup.prefixedEmail(label);
    }

    public static String uniquePhone(String label) {
        return TestDataCleanup.prefixedPhone(label);
    }

    public static String uniqueName(String label) {
        return TestDataCleanup.prefixedFullName(label);
    }

    public static Map<String, Object> registerRequest(String email, String phone, String password, String role) {
        Map<String, Object> request = new LinkedHashMap<>();
        request.put("fullName", uniqueName(role.toLowerCase() + " user"));
        request.put("email", email);
        request.put("phone", phone);
        request.put("password", password);
        request.put("confirmPassword", password);
        request.put("role", role);
        request.put("address", "Generated by ApiTestDataFactory");
        if ("ROLE_DRIVER".equals(role)) {
            request.put("ambulanceRegistrationNumber", "AMB-" + System.currentTimeMillis());
        }
        return request;
    }

    public static Map<String, Object> bookingRequest(String contactName, String contactPhone) {
        Map<String, Object> request = new LinkedHashMap<>();
        request.put("contactName", contactName);
        request.put("contactPhone", contactPhone);
        request.put("pickupAddress", "Test pickup address");
        request.put("pickupLatitude", 12.9716);
        request.put("pickupLongitude", 77.5946);
        request.put("destinationAddress", "Test destination hospital");
        request.put("destinationLatitude", 12.9780);
        request.put("destinationLongitude", 77.6000);
        request.put("patientCondition", "Chest pain");
        request.put("ambulanceType", "ADVANCED_LIFE_SUPPORT");
        request.put("bookingChannel", "ONLINE_WEB");
        return request;
    }

    public static Map<String, Object> driverLocationUpdateRequest(double latitude, double longitude) {
        Map<String, Object> request = new LinkedHashMap<>();
        request.put("latitude", latitude);
        request.put("longitude", longitude);
        return request;
    }

    public static Map<String, Object> driverAvailabilityRequest(String availabilityStatus, Double latitude, Double longitude) {
        Map<String, Object> request = new LinkedHashMap<>();
        request.put("availabilityStatus", availabilityStatus);
        if (latitude != null) {
            request.put("latitude", latitude);
        }
        if (longitude != null) {
            request.put("longitude", longitude);
        }
        return request;
    }

    public static Map<String, Object> nearestDriverQuery(double pickupLatitude, double pickupLongitude,
                                                        double destinationLatitude, double destinationLongitude) {
        Map<String, Object> query = new LinkedHashMap<>();
        query.put("pickupLatitude", pickupLatitude);
        query.put("pickupLongitude", pickupLongitude);
        query.put("destinationLatitude", destinationLatitude);
        query.put("destinationLongitude", destinationLongitude);
        return query;
    }

    public static Map<String, Object> locationUpdateRequest(double latitude, double longitude) {
        Map<String, Object> request = new LinkedHashMap<>();
        request.put("latitude", latitude);
        request.put("longitude", longitude);
        request.put("speedKmh", 32.5);
        request.put("headingDegrees", 90.0);
        return request;
    }

    public static Map<String, Object> statusUpdateRequest(String status, String cancellationReason) {
        Map<String, Object> request = new LinkedHashMap<>();
        request.put("status", status);
        if (cancellationReason != null) {
            request.put("cancellationReason", cancellationReason);
        }
        return request;
    }

    public static Map<String, Object> assignDriverRequest(Long driverId) {
        Map<String, Object> request = new LinkedHashMap<>();
        request.put("driverId", driverId);
        return request;
    }
}
